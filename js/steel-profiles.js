function getAvailableProfileTypes(module,standard){
  return Object.keys(PROFILE_USAGE).filter(function(t){
    if(!PROFILE_USAGE[t][module]) return false;
    if(standard && PROFILES[t] && PROFILES[t].std!==standard) return false;
    return true;
  });
}
function getProfileProperties(type,name){
  var p=PROFILES[type];if(!p) return null;
  for(var i=0;i<p.data.length;i++){if(p.data[i][0]===name) return p.data[i];}
  return null;
}
function getProfileDropdown(type){
  var p=PROFILES[type];if(!p) return {names:[],data:[]};
  return {names:p.data.map(function(r){return r[0];}),data:p.data};
}

